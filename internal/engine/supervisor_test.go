func TestSupervisorStartClearsPreviousVersion(t *testing.T) {
	runtime := NewSupervisor(Options{BinaryPath: "/bin/true", ConfigDir: t.TempDir()})
	runtime.mu.Lock()
	runtime.engineVersion = "previous"
	runtime.mu.Unlock()

	if err := runtime.Start(context.Background()); err == nil {
		t.Fatal("Start() error = nil, want a failure for an engine that exits immediately")
	}

	runtime.mu.Lock()
	version := runtime.engineVersion
	running := runtime.running
	runtime.mu.Unlock()
	if version != "" || running {
		t.Fatalf("after failed start version = %q, running = %v; want empty/false", version, running)
	}
}

