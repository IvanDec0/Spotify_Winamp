func TestWriteConfigEngineOptions(t *testing.T) {
	tests := []struct {
		name      string
		group     bool
		imageSize string
		wantGroup string
		wantImage string
	}{
		{name: "defaults", wantGroup: "false", wantImage: "default"},
		{name: "group and large", group: true, imageSize: "large", wantGroup: "true", wantImage: "large"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			runtime := NewRuntime(RuntimeOptions{DeviceIsGroup: test.group, ImageSize: test.imageSize})
			dir := t.TempDir()
			if err := runtime.writeConfig(12345, dir); err != nil {
				t.Fatalf("writeConfig: %v", err)
			}
			data, err := os.ReadFile(filepath.Join(dir, "config.yml"))
			if err != nil {
				t.Fatalf("read config: %v", err)
			}
			config := string(data)

			if got := yamlScalar(t, config, "device_is_group"); got != test.wantGroup {
				t.Fatalf("device_is_group = %q, want %q:\n%s", got, test.wantGroup, config)
			}
			if got := yamlScalar(t, config, "prefer_firewall_friendly_ports"); got != "true" {
				t.Fatalf("prefer_firewall_friendly_ports = %q, want true:\n%s", got, config)
			}
			server := yamlSection(t, config, "server")
			if !strings.Contains(server, "image_size: "+test.wantImage) {
				t.Fatalf("server section missing image_size: %s:\n%s", test.wantImage, server)
			}
			metadata := yamlSection(t, config, "metadata")
			if !strings.Contains(metadata, "max_tracks: 800") {
				t.Fatalf("metadata section missing max_tracks: 800:\n%s", metadata)
			}
			if strings.Contains(config, "accesspoint_ports") {
				t.Fatalf("generated config must not invite accesspoint_ports edits:\n%s", config)
			}
			if !strings.Contains(config, "generated by Cadence on every start") {
				t.Fatalf("config does not mark itself as generated:\n%s", config)
			}
		})
	}
}

func yamlScalar(t *testing.T, config, key string) string {
	t.Helper()
	for _, line := range strings.Split(config, "\n") {
		if strings.HasPrefix(line, key+":") {
			return strings.TrimSpace(strings.TrimPrefix(line, key+":"))
		}
	}
	t.Fatalf("config has no top-level %s:\n%s", key, config)
	return ""
}

func yamlSection(t *testing.T, config, name string) string {
	t.Helper()
	lines := strings.Split(config, "\n")
	start := -1
	for index, line := range lines {
		if line == name+":" {
			start = index
			break
		}
	}
	if start == -1 {
		t.Fatalf("config has no top-level %s section:\n%s", name, config)
	}
	var section strings.Builder
	for _, line := range lines[start+1:] {
		if line != "" && !strings.HasPrefix(line, " ") && !strings.HasPrefix(line, "\t") {
			break
		}
		section.WriteString(line)
		section.WriteString("\n")
	}
	return section.String()
}

func TestNewRuntimeValidatesImageSize(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  string
	}{
		{name: "empty", input: "", want: "default"},
		{name: "default", input: "default", want: "default"},
		{name: "small", input: "small", want: "small"},
		{name: "large", input: "large", want: "large"},
		{name: "xlarge", input: "xlarge", want: "xlarge"},
		{name: "unknown", input: "huge", want: "default"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			runtime := NewRuntime(RuntimeOptions{ImageSize: test.input})
			if runtime.imageSize != test.want {
				t.Fatalf("imageSize = %q, want %q", runtime.imageSize, test.want)
			}
		})
	}
}

func TestRuntimeParsesEngineVersionFromLog(t *testing.T) {
	logPath := filepath.Join(t.TempDir(), "go-librespot.log")
	line := `time="2026-11-04T08:55:32Z" level=info msg="running go-librespot 0.10.6-20261104085532-16b65bb4cd2b"` + "\n"
	if err := os.WriteFile(logPath, []byte(line), 0o600); err != nil {
		t.Fatalf("write log: %v", err)
	}

	runtime := &Runtime{running: true, logPath: logPath}
	const want = "0.10.6-20261104085532-16b65bb4cd2b"
	if got := runtime.Version(); got != want {
		t.Fatalf("Version() = %q, want %q", got, want)
	}
	if err := os.Remove(logPath); err != nil {
		t.Fatalf("remove log: %v", err)
	}
	if got := runtime.Version(); got != want {
		t.Fatalf("cached Version() = %q, want %q", got, want)
	}
}

